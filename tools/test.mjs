import fs from 'node:fs';
import { whenText, buildFamily, relate, childrenView, resolve, buildChain, childrenViewOfChain } from '../js/kinship.js';
const data = JSON.parse(fs.readFileSync(new URL('../data/sample-family.json', import.meta.url)));
const fam = buildFamily(data.people);
const P = id => fam.byId.get(id);
const fmt = r => {
  if (!r) return '-';
  if (r.kind === 'either') return r.options.map(o => (o.term ? o.term.zh + '/' + o.term.ts : 'name(' + (o.ref?.zh || '') + ')') + ' ' + whenText(r.who, o.older)).join(' | ');
  if (r.kind === 'junior') return 'name(' + (r.ref?.zh || '?') + ')';
  if (r.term) return r.term.zh + ' ' + r.term.py + ' / ' + r.term.tc + ' ' + r.term.ts + (r.general ? ' [general]' : '');
  return r.kind;
};
let fail = 0;
function check(spk, tgt, expectZh) {
  const { result, en } = relate(fam, P(spk), P(tgt));
  const out = fmt(result);
  const ok = out.startsWith(expectZh);
  if (!ok) fail++;
  console.log((ok ? 'ok  ' : 'FAIL') + ` ${spk} -> ${tgt}: ${en} = ${out}  (expect ${expectZh})`);
}
